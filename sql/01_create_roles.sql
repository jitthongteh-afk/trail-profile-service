USE [Assessment1DB];
GO

IF OBJECT_ID(N'CW2.ROLE', N'U') IS NULL
BEGIN
    CREATE TABLE CW2.ROLE
    (
        RoleID INT NOT NULL,
        RoleName VARCHAR(50) NOT NULL,
        CONSTRAINT PK_CW2_ROLE PRIMARY KEY (RoleID),
        CONSTRAINT UQ_CW2_ROLE_RoleName UNIQUE (RoleName)
    );
END;
GO

IF NOT EXISTS (SELECT 1 FROM CW2.ROLE WHERE RoleID = 1)
BEGIN
    INSERT INTO CW2.ROLE (RoleID, RoleName)
    VALUES (1, 'Member');
END;

IF NOT EXISTS (SELECT 1 FROM CW2.ROLE WHERE RoleID = 2)
BEGIN
    INSERT INTO CW2.ROLE (RoleID, RoleName)
    VALUES (2, 'Admin');
END;
GO

SELECT RoleID, RoleName
FROM CW2.ROLE
ORDER BY RoleID;
GO